local plt = require("luaplotlib")

test("shaded spans are unhatched by default", function()
  local fig = plt.figure()
  fig:axhspan(1, 2)
  assert_not_contains(fig:to_svg(), '<pattern id="hatch-')
  assert_equal(fig:to_scene().series[1].style.hatch, nil)
end)

test("axhspan and axvspan support hatches", function()
  local fig = plt.figure()
  fig:axhspan(1, 2, { hatch = "/" })
  fig:axvspan(3, 4, { hatch = "+" })
  local svg = fig:to_svg()
  assert_contains(svg, '<pattern id="hatch-')
  local hatched = select(2, svg:gsub('class="span axhspan"[^>]*fill="url%(#hatch%-', ""))
  assert_equal(hatched, 1)
  local vertical = select(2, svg:gsub('class="span axvspan"[^>]*fill="url%(#hatch%-', ""))
  assert_equal(vertical, 1)
  local scene = fig:to_scene()
  assert_equal(scene.series[1].style.hatch, "/")
  assert_equal(scene.series[2].style.hatch, "+")
end)

test("span hatch validates supported patterns", function()
  local fig = plt.figure()
  assert_error("hatch must be", function()
    fig:axhspan(1, 2, { hatch = "*" })
  end)
  assert_error("hatch must be", function()
    fig:axvspan(1, 2, { hatch = 7 })
  end)
end)
