local plt = require("luaplotlib")

test("annotations are upright by default", function()
  local fig = plt.figure()
  fig:plot({ 1, 2 }, { 1, 2 })
  fig:annotate("peak", 1, 2)
  local svg = fig:to_svg()
  assert_not_contains(svg, 'class="annotation-text" transform=')
  assert_equal(fig:to_scene().annotations[1].rotation, 0)
end)

test("cartesian and polar annotations rotate around their text anchor", function()
  local cartesian = plt.figure()
  cartesian:plot({ 1, 2 }, { 1, 2 })
  cartesian:annotate("rotated", 1, 2, { rotation = 30 })
  local svg = cartesian:to_svg()
  assert_match(svg, 'class="annotation%-text"[^>]*transform="rotate%(30 [^)]*%)"')
  assert_equal(cartesian:to_scene().annotations[1].rotation, 30)

  local polar = plt.figure({ width = 480, height = 480 })
  polar:polar({ 0, 1 }, { 1, 1 })
  polar:annotate("polar", 0.5, 2, { rotation = -45 })
  assert_match(polar:to_svg(),
    'class="annotation%-text"[^>]*transform="rotate%(%-45 [^)]*%)"')
  assert_equal(polar:to_scene().annotations[1].rotation, -45)
end)

test("annotation rotation validates finite bounds", function()
  local fig = plt.figure()
  assert_error("rotation must be <= 180", function()
    fig:annotate("x", 1, 1, { rotation = 181 })
  end)
  assert_error("rotation must be >= %-180", function()
    fig:annotate("x", 1, 1, { rotation = -181 })
  end)
  assert_error("rotation must be a number", function()
    fig:annotate("x", 1, 1, { rotation = "tilted" })
  end)
end)
