local plt = require("luaplotlib")

test("formats x ticks as calendar dates", function()
  local fig = plt.figure({ width = 640, height = 400 })
  local base = os.time({ year = 2026, month = 1, day = 1, hour = 12 })
  fig:plot({ base, base + 86400, base + 172800 }, { 1, 2, 3 })
  fig:xdate("%Y-%m-%d")
  local svg = fig:to_svg()
  assert_match(svg, "%d%d%d%d%-%d%d%-%d%d")
  assert_error("string", function() fig:xdate(123) end)
end)

test("wraps SVG in a standalone HTML document", function()
  local fig = plt.figure({ width = 320, height = 240 })
  fig:plot({ 1, 2 }, { 2, 1 })
  local html = fig:to_html("A plot & more")
  assert_contains(html, "<!doctype html>")
  assert_contains(html, "<svg")
  assert_contains(html, "A plot &amp; more")
  local path = (TMPDIR or "/tmp") .. "/luaplotlib.html"
  assert_equal(fig:save_html(path, "Title"), path)
  local handle = assert(io.open(path, "rb"))
  assert_contains(handle:read("*a"), "<!doctype html>")
  handle:close()
  os.remove(path)
end)
