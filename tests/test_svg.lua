-- SVG document structure, escaping, axes, grid, legends, and file output.

local plt = require("luaplotlib")

test("SVG is standalone with width, height, and viewBox", function()
  local fig = plt.figure({ width = 720, height = 540, dpi = 120 })
  fig:plot({ 1, 2, 3 }, { 2, 3, 1 })
  local svg = fig:to_svg()
  assert_true(svg:sub(1, 5) == "<?xml", "must have an XML declaration")
  assert_contains(svg, 'xmlns="http://www.w3.org/2000/svg"')
  assert_contains(svg, 'width="720" height="540" viewBox="0 0 720 540"')
  assert_contains(svg, 'data-dpi="120"')
  assert_contains(svg, '<desc>Generated by luaplotlib')
  assert_contains(svg, "</svg>\n")
  assert_not_contains(svg, "http://www.w3.org/1999/xlink")
  assert_not_contains(svg, "<image")
  assert_well_formed_svg(svg)
end)

test("user text is XML-escaped in labels, titles, and attributes", function()
  local fig = plt.figure()
  fig:title([[A & B <C> "D" 'E']])
  fig:xlabel("x < y & z")
  fig:ylabel([[quoted "ylabel" & more]])
  fig:plot({ 1, 2 }, { 2, 1 }, { label = "series & <tag>" })
  fig:legend()
  local svg = fig:to_svg()

  assert_contains(svg, "A &amp; B &lt;C&gt; &quot;D&quot; &apos;E&apos;")
  assert_contains(svg, "x &lt; y &amp; z")
  assert_contains(svg, "quoted &quot;ylabel&quot; &amp; more")
  assert_contains(svg, "series &amp; &lt;tag&gt;")
  assert_not_contains(svg, "<C>")
  assert_not_contains(svg, "series & <tag>")
  assert_well_formed_svg(svg)
end)

test("invalid XML control characters are removed from output", function()
  local fig = plt.figure()
  fig:title("control" .. string.char(1) .. "character")
  local svg = fig:to_svg()
  assert_not_contains(svg, string.char(1))
  assert_contains(svg, "control\239\191\189character")
  assert_well_formed_svg(svg)
end)

test("unicode labels are preserved", function()
  local fig = plt.figure()
  fig:title("Temperatur °C — café")
  fig:plot({ 1, 2 }, { 1, 2 }, { label = "målinger" })
  fig:legend()
  local svg = fig:to_svg()
  assert_contains(svg, "Temperatur °C — café")
  assert_contains(svg, "målinger")
  assert_well_formed_svg(svg)
end)

test("axes render spines, tick marks, and numeric tick labels", function()
  local fig = plt.figure()
  fig:plot({ 1, 2, 3 }, { 10, 20, 30 })
  local svg = fig:to_svg()
  assert_contains(svg, 'class="spine"')
  assert_contains(svg, '<g class="ticks x-ticks">')
  assert_contains(svg, '<g class="ticks y-ticks">')
  assert_true(count_occurrences(svg, 'class="tick-label"') >= 6,
    "expected several x and y tick labels")
  assert_true(count_occurrences(svg, 'class="tick-mark"') >= 6,
    "expected several x and y tick marks")
  assert_contains(svg, ">10</text>")
  assert_contains(svg, ">30</text>")
  assert_well_formed_svg(svg)
end)

test("titles and axis labels use dedicated classes", function()
  local fig = plt.figure()
  fig:plot({ 1, 2 }, { 1, 2 })
  fig:title("Main title")
  fig:xlabel("horizontal")
  fig:ylabel("vertical")
  local svg = fig:to_svg()
  assert_contains(svg, 'class="title"')
  assert_contains(svg, 'class="xlabel"')
  assert_contains(svg, 'class="ylabel"')
  assert_contains(svg, ">Main title</text>")
  assert_contains(svg, ">horizontal</text>")
  assert_contains(svg, ">vertical</text>")
  assert_contains(svg, "transform=\"rotate(-90 ")
  assert_well_formed_svg(svg)
end)

test("grid is off by default and can be enabled or disabled", function()
  local plain = plt.figure()
  plain:plot({ 1, 2 }, { 1, 2 })
  assert_not_contains(plain:to_svg(), 'class="grid"')

  local gridded = plt.figure()
  gridded:plot({ 1, 2 }, { 1, 2 })
  gridded:grid(true)
  local svg = gridded:to_svg()
  assert_contains(svg, '<g class="grid"')
  assert_true(count_occurrences(svg, '<g class="grid"') == 1)
  assert_well_formed_svg(svg)

  gridded:grid(false)
  assert_not_contains(gridded:to_svg(), 'class="grid"')
end)

test("legend renders frames, swatches, labels, and alternative locations", function()
  local fig = plt.figure()
  fig:plot({ 1, 2 }, { 1, 2 }, { label = "line" })
  fig:scatter({ 1.5 }, { 1.5 }, { label = "point" })
  fig:bar({ "x" }, { 1 }, { label = "bar" })
  fig:legend({ loc = "lower left", frame = false })
  local svg = fig:to_svg()
  assert_contains(svg, '<g class="legend">')
  assert_contains(svg, ">line</text>")
  assert_contains(svg, ">point</text>")
  assert_contains(svg, ">bar</text>")
  assert_not_contains(svg, 'class="legend-frame"')
  assert_well_formed_svg(svg)
end)

test("unlabeled series do not create a legend", function()
  local fig = plt.figure()
  fig:plot({ 1, 2 }, { 1, 2 })
  fig:legend()
  assert_not_contains(fig:to_svg(), '<g class="legend">')
end)

test("data is clipped to the axes rectangle", function()
  local fig = plt.figure()
  fig:plot({ 1, 2, 3 }, { 1, 2, 3 })
  fig:xlim(1.5, 2.5)
  fig:ylim(1.5, 2.5)
  local svg = fig:to_svg()
  assert_contains(svg, 'clip-path="url(#luaplotlib-plot-clip-')
  assert_contains(svg, '<clipPath id="luaplotlib-plot-clip-')
  assert_well_formed_svg(svg)
end)

test("savefig writes the same standalone SVG returned by to_svg", function()
  local fig = plt.figure()
  fig:plot({ 1, 2, 3 }, { 3, 2, 1 }, { label = "down" })
  fig:title("file output")
  fig:legend()
  local path = TEST_OUTPUT_DIR .. "/write-test.svg"
  local returned = fig:savefig(path)
  assert_equal(returned, path)
  local handle = assert(io.open(path, "rb"))
  local contents = assert(handle:read("*a"))
  handle:close()
  assert_true(#contents > 100)
  assert_equal(contents, fig:to_svg())
  assert_well_formed_svg(contents)
  assert_contains(contents, 'class="legend"')
end)

test("renderer is deterministic for one figure", function()
  local fig = plt.figure()
  fig:plot({ 1, 2, 3 }, { 1, 3, 2 })
  assert_equal(fig:to_svg(), fig:to_svg())
end)
