test("legend supports columns and a title", function()
  local fig = plt.figure()
  fig:plot({1,2}, {1,2}, { label = "one" })
  fig:plot({1,2}, {2,1}, { label = "two" })
  fig:legend({ ncol = 2, title = "Series" })
  local svg = fig:to_svg()
  assert_contains(svg, 'legend-title')
  assert_contains(svg, '>Series<')
  assert_contains(svg, '>one<'); assert_contains(svg, '>two<')
  local ok = pcall(function() fig:legend({ ncol = 0 }) end)
  assert_equal(ok, false)
end)
