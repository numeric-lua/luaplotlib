local plt = require("luaplotlib")

test("renders a secondary y axis and twin series", function()
  local fig = plt.figure({ width = 700, height = 460 })
  fig:plot({ 1, 2, 3 }, { 10, 20, 30 }, { label = "left" })
  local twin = fig:twinx()
  assert_true(twin == fig:twinx())
  twin:plot({ 1, 2, 3 }, { 100, 80, 60 }, { color = "#d62728" })
  twin:ylabel("right")
  twin:ylim(50, 110)
  local svg = fig:to_svg()
  assert_contains(svg, 'class="twin-axis"')
  assert_contains(svg, 'twin-series')
  assert_contains(svg, '>right<')
  assert_contains(svg, '>100<')
  assert_contains(svg, "#d62728")
end)

test("twin axis supports scatter and error bars", function()
  local fig = plt.figure()
  local twin = fig:twinx()
  twin:scatter({ 1, 2 }, { 5, 6 })
  twin:errorbar({ 1, 2 }, { 5, 6 }, { 0.5, 0.5 })
  local svg = fig:to_svg()
  assert_contains(svg, 'class="twin-axis"')
  assert_contains(svg, 'series-scatter')
end)
