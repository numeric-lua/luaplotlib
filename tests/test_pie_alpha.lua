local plt = require("luaplotlib")

test("pie accepts per-slice alpha", function()
  local fig = plt.figure()
  fig:pie({ 1, 2, 3 }, { alpha = { 0.2, 0.6, 1 } })
  local svg = fig:to_svg()
  assert_contains(svg, 'data-alpha="true"')
  assert_match(svg, 'class="pie%-slice"[^>]*fill%-opacity="0.2"')
  assert_match(svg, 'class="pie%-slice"[^>]*fill%-opacity="0.6"')
  local scene = fig:to_scene().pie
  assert_equal(scene.alphas[2], 0.6)
end)

test("pie accepts a scalar alpha and validates arrays", function()
  local fig = plt.figure()
  fig:pie({ 1, 2 }, { alpha = 0.5 })
  assert_contains(fig:to_svg(), 'fill-opacity="0.5"')
  assert_error("one entry per slice", function()
    fig:pie({ 1, 2, 3 }, { alpha = { 0.5 } })
  end)
  assert_error("alpha%[2%] must be <= 1", function()
    fig:pie({ 1, 2 }, { alpha = { 0.5, 2 } })
  end)
end)
