local plt = require("luaplotlib")

test("cartesian annotations accept bold weight", function()
  local fig = plt.figure()
  fig:plot({ 1, 2 }, { 1, 2 })
  fig:annotate("peak", 1.5, 1.5, { fontweight = "bold" })
  assert_match(fig:to_svg(), 'class="annotation%-text"[^>]*font%-weight="bold"')
  assert_equal(fig:to_scene().annotations[1].fontweight, "bold")
end)

test("polar annotations accept bold weight", function()
  local fig = plt.figure({ width = 480, height = 480 })
  fig:polar({ 0, 1 }, { 1, 1 })
  fig:polar_annotate("point", 0.5, 1, { fontweight = "bold" })
  assert_match(fig:to_svg(), 'class="annotation%-text"[^>]*font%-weight="bold"')
  assert_equal(fig:to_scene().annotations[1].fontweight, "bold")
end)

test("annotation fontweight validates allowed values", function()
  local fig = plt.figure()
  assert_error("fontweight must be 'normal' or 'bold'", function()
    fig:annotate("x", 1, 1, { fontweight = "heavy" })
  end)
end)
