local plt = require("luaplotlib")

local function plot_box(svg)
  local left, top, right, bottom = svg:match(
    '<path class="spine" d="M ([%d%.%-]+) ([%d%.%-]+) L [%d%.%-]+ [%d%.%-]+ L ([%d%.%-]+) ([%d%.%-]+)"')
  assert_true(left ~= nil, "could not read the plot box from the SVG")
  return tonumber(left), tonumber(top), tonumber(right), tonumber(bottom)
end

local function metadata_number(svg, name)
  local value = svg:match('data%-' .. name .. '="([%d%.%-]+)"')
  assert_true(value ~= nil, "missing data-" .. name .. " metadata")
  return tonumber(value)
end

test("aspect equal makes equal data spans square", function()
  local fig = plt.figure({ width = 700, height = 520 })
  fig:plot({ 0, 10 }, { 0, 10 })
  fig:xlim(0, 10)
  fig:ylim(0, 10)
  fig:aspect("equal")
  local svg = fig:to_svg()
  assert_contains(svg, 'data-aspect="equal"')
  local width = metadata_number(svg, "plot%-width")
  local height = metadata_number(svg, "plot%-height")
  assert_true(math.abs(width - height) < 0.002,
    "equal aspect should produce a square plot box")
  local left, top, right, bottom = plot_box(svg)
  assert_true(math.abs((right - left) - (bottom - top)) < 0.002)
  assert_well_formed_svg(svg)

  local scene = fig:to_scene()
  assert_equal(scene.aspect, 1)
  assert_equal(scene.aspect_mode, "equal")
  assert_equal(scene.aspect_adjustable, "box")
end)

test("numeric aspect uses the requested y-unit to x-unit ratio", function()
  local fig = plt.figure({ width = 720, height = 480 })
  fig:plot({ 0, 10 }, { 0, 5 })
  fig:xlim(0, 10)
  fig:ylim(0, 5)
  fig:aspect(2)
  local svg = fig:to_svg()
  assert_contains(svg, 'data-aspect="2"')
  local width = metadata_number(svg, "plot%-width")
  local height = metadata_number(svg, "plot%-height")
  -- aspect 2 with a 2:1 data span should be square.
  assert_true(math.abs(width - height) < 0.002)
  local scene = fig:to_scene()
  assert_equal(scene.aspect, 2)
  assert_equal(scene.aspect_mode, "numeric")
end)

test("aspect applies to log axes and can be reset to auto", function()
  local fig = plt.figure({ width = 680, height = 500 })
  fig:plot({ 1, 10, 100 }, { 1, 10, 100 })
  fig:xscale("log")
  fig:yscale("log")
  fig:aspect(0.5)
  local svg = fig:to_svg()
  local width = metadata_number(svg, "plot%-width")
  local height = metadata_number(svg, "plot%-height")
  assert_true(math.abs((height / width) - 0.5) < 0.002)

  fig:aspect("auto")
  local reset = fig:to_svg()
  assert_not_contains(reset, 'data-aspect=')
  assert_not_contains(reset, 'data-plot-width=')
  assert_true(not reset:find('data%-plot%-height='))
  assert_well_formed_svg(reset)
end)

test("aspect validates values and extreme layouts", function()
  local fig = plt.figure()
  assert_error("positive", function() fig:aspect(0) end)
  assert_error("positive", function() fig:aspect(-2) end)
  assert_error("aspect must be", function() fig:aspect("wide") end)

  local narrow = plt.figure({ width = 400, height = 300 })
  narrow:plot({ 0, 1 }, { 0, 1000 })
  narrow:xlim(0, 1)
  narrow:ylim(0, 1000)
  narrow:aspect(1)
  assert_error("leaves no drawable", function() narrow:to_svg() end)
end)
