local plt = require("luaplotlib")

test("titles default to normal weight and accept bold", function()
  local fig = plt.figure()
  fig:plot({ 1, 2 }, { 1, 2 })
  fig:title("plain")
  assert_not_contains(fig:to_svg(), 'class="title"[^>]*font-weight')
  fig:title("bold", { fontweight = "bold" })
  local svg = fig:to_svg()
  assert_match(svg, 'class="title"[^>]*font%-weight="bold"')
  assert_equal(fig:to_scene().title_fontweight, "bold")
end)

test("title fontweight carries through pie, polar, and subplots", function()
  local pie = plt.figure()
  pie:pie({ 1, 2 })
  pie:title("pie", { fontweight = "bold" })
  assert_match(pie:to_svg(), 'class="title"[^>]*font%-weight="bold"')

  local polar = plt.figure({ width = 480, height = 480 })
  polar:polar({ 0, 1 }, { 1, 1 })
  polar:title("polar", { fontweight = "bold" })
  assert_match(polar:to_svg(), 'class="title"[^>]*font%-weight="bold"')

  local subplots = plt.subplots(1, 1)
  subplots:title("grid", { fontweight = "bold" })
  assert_match(subplots:to_svg(), 'class="suptitle"[^>]*font%-weight="bold"')
end)

test("title fontweight validates allowed values", function()
  local fig = plt.figure()
  assert_error("fontweight must be 'normal' or 'bold'", function()
    fig:title("x", { fontweight = "heavy" })
  end)
end)
