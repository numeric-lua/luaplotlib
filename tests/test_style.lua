local plt = require("luaplotlib")

test("supports grid styling, facecolor, and aria labels", function()
  local fig = plt.figure({ width = 400, height = 300 })
  fig:plot({ 1, 2 }, { 2, 1 })
  fig:grid(true, { color = "#ff0000", linewidth = 2, linestyle = "dashed" })
  fig:facecolor("#f0f0f0")
  fig:aria_label("styled plot")
  local svg = fig:to_svg()
  assert_contains(svg, 'fill="#f0f0f0"')
  assert_contains(svg, 'stroke="#ff0000" stroke-width="2" stroke-dasharray="6 4"')
  assert_contains(svg, 'aria-label="styled plot"')
  assert_error("dashed", function() fig:grid(true, { linestyle = "bad" }) end)
end)
