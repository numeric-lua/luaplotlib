local plt = require("luaplotlib")

test("legend markerfirst defaults to true and can be disabled", function()
  local fig = plt.figure()
  fig:plot({ 1, 2 }, { 1, 2 }, { label = "line" })
  fig:legend()
  assert_contains(fig:to_svg(), 'data-markerfirst="true"')
  assert_equal(fig:to_scene().legend_style.markerfirst, true)

  fig:legend({ markerfirst = false })
  local svg = fig:to_svg()
  assert_contains(svg, 'data-markerfirst="false"')
  assert_equal(fig:to_scene().legend_style.markerfirst, false)
end)

test("polar legend markerfirst is applied and exported", function()
  local fig = plt.figure({ width = 520, height = 520 })
  fig:polar({ 0, 1 }, { 1, 1 }, { label = "p" })
  fig:legend({ markerfirst = false })
  assert_contains(fig:to_svg(), 'data-markerfirst="false"')
  assert_equal(fig:to_scene().polar.legend.markerfirst, false)
end)

test("legend markerfirst validates the boolean", function()
  local fig = plt.figure()
  assert_error("markerfirst must be a boolean", function()
    fig:legend({ markerfirst = "no" })
  end)
end)
