local plt = require("luaplotlib")

test("legend title font size follows the label size by default", function()
  local fig = plt.figure()
  fig:plot({ 1, 2 }, { 1, 2 }, { label = "line" })
  fig:legend({ title = "series" })
  assert_contains(fig:to_svg(), 'data-fontsize="11" data-title-fontsize="11"')
  assert_equal(fig:to_scene().legend_style.title_fontsize, 11)
end)

test("legend title font size can differ from labels", function()
  local fig = plt.figure()
  fig:plot({ 1, 2 }, { 1, 2 }, { label = "line" })
  fig:legend({ title = "series", fontsize = 12, title_fontsize = 17 })
  local svg = fig:to_svg()
  assert_contains(svg, 'data-fontsize="12" data-title-fontsize="17"')
  assert_match(svg, 'class="legend%-title"[^>]*font%-size="17"')
  local style = fig:to_scene().legend_style
  assert_equal(style.fontsize, 12)
  assert_equal(style.title_fontsize, 17)

  local polar = plt.figure({ width = 520, height = 520 })
  polar:polar({ 0, 1 }, { 1, 1 }, { label = "p" })
  polar:legend({ title = "polar", title_fontsize = 15 })
  assert_contains(polar:to_svg(), 'data-title-fontsize="15"')
  assert_equal(polar:to_scene().polar.legend.title_fontsize, 15)
end)

test("legend title font size validates positive numbers", function()
  local fig = plt.figure()
  assert_error("title_fontsize must be >= 0.1", function()
    fig:legend({ title = "x", title_fontsize = 0 })
  end)
end)
