local plt = require("luaplotlib")

test("legend label weight is configurable", function()
  local fig = plt.figure()
  fig:plot({ 1, 2 }, { 1, 2 }, { label = "line" })
  fig:legend({ fontweight = "bold" })
  local svg = fig:to_svg()
  assert_contains(svg, 'data-fontweight="bold"')
  assert_match(svg, '<text x="[^"]*" y="[^"]*" font%-size="11" fill="#222222" font%-weight="bold">line</text>')
  assert_equal(fig:to_scene().legend_style.fontweight, "bold")
end)

test("polar legend label weight is exported", function()
  local fig = plt.figure({ width = 520, height = 520 })
  fig:polar({ 0, 1 }, { 1, 1 }, { label = "p" })
  fig:legend({ fontweight = "bold" })
  assert_contains(fig:to_svg(), 'data-fontweight="bold"')
  assert_equal(fig:to_scene().polar.legend.fontweight, "bold")
end)

test("legend fontweight validates allowed values", function()
  local fig = plt.figure()
  assert_error("fontweight must be 'normal' or 'bold'", function()
    fig:legend({ fontweight = "heavy" })
  end)
end)
