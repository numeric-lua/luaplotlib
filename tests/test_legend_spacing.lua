local plt = require("luaplotlib")

test("legend spacing keeps its defaults", function()
  local fig = plt.figure()
  fig:plot({ 1, 2 }, { 1, 2 }, { label = "line" })
  fig:legend()
  local svg = fig:to_svg()
  assert_contains(svg, 'data-borderpad="8" data-handlelength="20"')
  local style = fig:to_scene().legend_style
  assert_equal(style.borderpad, 8)
  assert_equal(style.handlelength, 20)
end)

test("cartesian legend borderpad and handlelength are configurable", function()
  local fig = plt.figure()
  fig:plot({ 1, 2 }, { 1, 2 }, { label = "line" })
  fig:legend({ borderpad = 12, handlelength = 30 })
  local svg = fig:to_svg()
  assert_contains(svg, 'data-borderpad="12" data-handlelength="30"')
  local style = fig:to_scene().legend_style
  assert_equal(style.borderpad, 12)
  assert_equal(style.handlelength, 30)
end)

test("polar legend spacing is applied and exported", function()
  local fig = plt.figure({ width = 520, height = 520 })
  fig:polar({ 0, 1 }, { 1, 1 }, { label = "line" })
  fig:legend({ borderpad = 11, handlelength = 26 })
  local svg = fig:to_svg()
  assert_contains(svg, 'data-borderpad="11" data-handlelength="26"')
  local legend = fig:to_scene().polar.legend
  assert_equal(legend.borderpad, 11)
  assert_equal(legend.handlelength, 26)
end)

test("legend spacing validates non-negative numbers", function()
  local fig = plt.figure()
  assert_error("borderpad must be >= 0", function()
    fig:legend({ borderpad = -1 })
  end)
  assert_error("handlelength must be a number", function()
    fig:legend({ handlelength = "long" })
  end)
end)
