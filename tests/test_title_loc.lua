local plt = require("luaplotlib")

test("cartesian titles are centered by default", function()
  local fig = plt.figure()
  fig:plot({ 1, 2 }, { 1, 2 })
  fig:title("center")
  local svg = fig:to_svg()
  assert_match(svg, 'class="title" x="[^"]*" y="[^"]*" font%-size="18" fill="#222222" text%-anchor="middle">center</text>')
  assert_equal(fig:to_scene().title_align, "center")
end)

test("cartesian titles can be aligned left or right", function()
  local left = plt.figure()
  left:plot({ 1, 2 }, { 1, 2 })
  left:title("left", { loc = "left" })
  local left_svg = left:to_svg()
  assert_contains(left_svg, 'text-anchor="start">left</text>')
  assert_equal(left:to_scene().title_align, "left")

  local right = plt.figure()
  right:plot({ 1, 2 }, { 1, 2 })
  right:title("right", { loc = "right" })
  assert_contains(right:to_svg(), 'text-anchor="end">right</text>')
  assert_equal(right:to_scene().title_align, "right")
end)

test("title alignment carries through pie, polar, and subplot renderers", function()
  local pie = plt.figure()
  pie:pie({ 1, 2, 3 }, { labels = { "a", "b", "c" } })
  pie:title("pie", { loc = "left" })
  assert_match(pie:to_svg(), 'class="title" x="[^"]*" y="28" font%-size="18" fill="#222222" text%-anchor="start">pie</text>')

  local polar = plt.figure({ width = 480, height = 480 })
  polar:polar({ 0, 1 }, { 1, 1 })
  polar:title("polar", { loc = "right" })
  assert_match(polar:to_svg(), 'class="title" x="[^"]*" y="30" font%-size="18" fill="#222222" text%-anchor="end">polar</text>')
  assert_equal(polar:to_scene().title_align, "right")

  local subplots = plt.subplots(1, 2, { width = 640, height = 360 })
  subplots:title("grid", { loc = "right" })
  assert_match(subplots:to_svg(), 'class="suptitle" x="[^"]*" y="[^"]*" font%-size="20" fill="#222222" text%-anchor="end">grid</text>')
  assert_equal(subplots:to_scene().title_align, "right")
end)

test("title loc validates accepted values and option names", function()
  local fig = plt.figure()
  assert_error("title loc must be left, center, or right", function()
    fig:title("bad", { loc = "middle" })
  end)
  assert_error("unsupported title option", function()
    fig:title("bad", { align = "left" })
  end)
  local subplots = plt.subplots(1, 1)
  assert_error("subplots title loc must be left, center, or right", function()
    subplots:title("bad", { loc = "middle" })
  end)
end)
