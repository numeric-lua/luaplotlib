local plt = require("luaplotlib")

test("tick labels keep their default style", function()
  local fig = plt.figure()
  fig:plot({ 1, 2 }, { 1, 2 })
  local svg = fig:to_svg()
  assert_not_contains(svg, "data-ticklabelsize")
  assert_match(svg, 'class="tick%-label" x="[^"]*" y="[^"]*" font%-size="11" fill="#222222"')
  local scene = fig:to_scene()
  assert_equal(scene.ticklabelsize, 11)
  assert_equal(scene.ticklabelcolor, "#222222")
end)

test("tick label size and color apply to both axes", function()
  local fig = plt.figure({ width = 720, height = 480 })
  fig:plot({ 1, 2 }, { 1, 2 })
  fig:ticklabelsize(14)
  fig:ticklabelcolor("#334155")
  local svg = fig:to_svg()
  assert_contains(svg, 'data-ticklabelsize="14" data-ticklabelcolor="#334155"')
  assert_match(svg, 'class="tick%-label" x="[^"]*" y="[^"]*" font%-size="14" fill="#334155"')
  assert_contains(svg, 'class="spine" d="M 75 48 L 75 411 L 692 411"')
  local scene = fig:to_scene()
  assert_equal(scene.ticklabelsize, 14)
  assert_equal(scene.ticklabelcolor, "#334155")
end)

test("tick label style validates size and color", function()
  local fig = plt.figure()
  assert_error("ticklabelsize must be >= 0.1", function()
    fig:ticklabelsize(0)
  end)
  assert_error("ticklabelsize must be a number", function()
    fig:ticklabelsize("large")
  end)
  assert_error("ticklabelcolor", function()
    fig:ticklabelcolor("12bad")
  end)
end)
