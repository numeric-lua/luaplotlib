local plt = require("luaplotlib")

test("creates a subplot grid and renders each axes", function()
  local figure, axes = plt.subplots(2, 2, {
    width = 800, height = 600, title = "Grid", gap = 10,
  })
  assert_equal(#axes, 2)
  assert_equal(#axes[1], 2)
  axes[1][1]:plot({ 1, 2, 3 }, { 3, 2, 1 })
  axes[1][1]:title("A")
  axes[2][2]:scatter({ 1, 2 }, { 2, 3 }, { label = "points" })
  axes[2][2]:legend()
  local svg = figure:to_svg()
  assert_true(svg:find('class="suptitle"', 1, true) ~= nil)
  assert_true(svg:find('data-subplots="2x2"', 1, true) ~= nil)
  assert_true(select(2, svg:gsub('class="subplot"', "")) == 4)
  local path = (TMPDIR or "/tmp") .. "/luaplotlib-subplots.svg"
  assert_equal(figure:savefig(path), path)
  local handle = assert(io.open(path, "rb"))
  local contents = handle:read("*a")
  handle:close()
  assert_true(#contents > #svg - 10)
  os.remove(path)
  local scene = figure:to_scene()
  assert_equal(scene.type, "luaplotlib.subplots")
  assert_equal(#scene.axes, 4)
end)

test("validates subplot grids and shares explicit limits", function()
  assert_error("positive integer", function() plt.subplots(0, 2) end)
  local figure, axes = plt.subplots(1, 2, { width = 600, height = 300 })
  axes[1][1]:plot({ 1, 2 }, { 1, 2 })
  axes[1][2]:plot({ 1, 2 }, { 5, 6 })
  axes[1][1]:xlim(0, 10)
  axes[1][2]:xlim(5, 15)
  figure:share_limits("x")
  assert_equal(axes[1][1]._xlim[1], 0)
  assert_equal(axes[1][1]._xlim[2], 15)
  assert_equal(axes[1][2]._xlim[1], 0)
end)

test("rotates crowded x tick labels", function()
  local fig = plt.figure({ width = 600, height = 400 })
  fig:bar({ "very long label one", "very long label two" }, { 1, 2 })
  fig:xtick_rotation(45)
  local svg = fig:to_svg()
  assert_contains(svg, 'rotate(45')
  assert_contains(svg, 'text-anchor="end"')
  assert_error("integer", function() fig:xtick_rotation(100) end)
end)
