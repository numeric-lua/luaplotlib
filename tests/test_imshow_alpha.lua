local plt = require("luaplotlib")

test("imshow is fully opaque by default", function()
  local fig = plt.figure()
  fig:imshow({ { 1, 2 }, { 3, 4 } })
  local svg = fig:to_svg()
  assert_not_contains(svg, "data-alpha")
  assert_not_contains(svg, "fill-opacity")
  assert_equal(fig:to_scene().series[1].style.alpha, 1)
end)

test("imshow alpha is applied to the heatmap cells", function()
  local fig = plt.figure()
  fig:imshow({ { 1, 2 }, { 3, 4 } }, { alpha = 0.4 })
  local svg = fig:to_svg()
  assert_contains(svg, 'class="heatmap" data-alpha="0.4"')
  local cells = select(2, svg:gsub('class="heatmap%-cell"', ""))
  assert_equal(cells, 4)
  local faded = select(2, svg:gsub('class="heatmap%-cell"[^>]*fill%-opacity="0.4"',
    ""))
  assert_equal(faded, 4)
  assert_equal(fig:to_scene().series[1].style.alpha, 0.4)
end)

test("imshow alpha validates the [0, 1] range", function()
  local fig = plt.figure()
  assert_error("imshow alpha must be <= 1", function()
    fig:imshow({ { 1, 2 }, { 3, 4 } }, { alpha = 1.2 })
  end)
  assert_error("alpha must be a number", function()
    fig:imshow({ { 1, 2 }, { 3, 4 } }, { alpha = "half" })
  end)
end)
