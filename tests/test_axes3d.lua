local plt = require("luaplotlib")
test("renders true 3-D axes, line, and scatter", function()
  local fig = plt.figure3d({ width = 600, height = 400 })
  fig:plot({ 0, 1 }, { 0, 1 }, { 0, 1 })
  fig:scatter({ 0.5 }, { 0.5 }, { 0.5 })
  fig:title("3D")
  local svg = fig:to_svg()
  assert_contains(svg, 'class="axes3d"')
  assert_contains(svg, 'class="series series-line"')
  assert_contains(svg, 'class="series series-scatter"')
  local path = (TMPDIR or "/tmp") .. "/axes3d.svg"
  assert_equal(fig:savefig(path), path)
  os.remove(path)
end)
