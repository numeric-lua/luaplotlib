local plt = require("luaplotlib")

test("barh supports a hatch pattern", function()
  local fig = plt.figure()
  fig:barh({ "A", "B" }, { 1, 2 }, { hatch = "/" })
  local svg = fig:to_svg()
  assert_contains(svg, '<pattern id="hatch-')
  local filled = select(2, svg:gsub('class="barh"[^>]*fill="url%(#hatch%-', ""))
  assert_equal(filled, 2)
  local style = fig:to_scene().series[1].style
  assert_equal(style.hatch, "/")
end)

test("bar hatch patterns are exported through the scene style", function()
  local fig = plt.figure()
  fig:bar({ "A", "B" }, { 1, 2 }, { hatch = { "x" } })
  local svg = fig:to_svg()
  assert_contains(svg, '<pattern id="hatch-')
  assert_equal(fig:to_scene().series[1].style.hatch, "x")
end)

test("barh hatch validates accepted patterns", function()
  local fig = plt.figure()
  assert_error("hatch must be", function()
    fig:barh({ "A" }, { 1 }, { hatch = "*" })
  end)
  assert_error("hatch must be", function()
    fig:barh({ "A" }, { 1 }, { hatch = 7 })
  end)
end)
