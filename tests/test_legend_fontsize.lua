local plt = require("luaplotlib")

test("legend font size keeps its default", function()
  local fig = plt.figure()
  fig:plot({ 1, 2 }, { 1, 2 }, { label = "line" })
  fig:legend()
  assert_contains(fig:to_svg(), 'data-fontsize="11"')
  assert_equal(fig:to_scene().legend_style.fontsize, 11)
end)

test("cartesian and polar legends accept a font size", function()
  local fig = plt.figure()
  fig:plot({ 1, 2 }, { 1, 2 }, { label = "line" })
  fig:legend({ fontsize = 16 })
  local svg = fig:to_svg()
  assert_contains(svg, 'data-fontsize="16"')
  assert_match(svg, '<text x="[^"]*" y="[^"]*" font%-size="16" fill="#222222">line</text>')
  assert_equal(fig:to_scene().legend_style.fontsize, 16)

  local polar = plt.figure({ width = 520, height = 520 })
  polar:polar({ 0, 1 }, { 1, 1 }, { label = "polar" })
  polar:legend({ fontsize = 14 })
  assert_contains(polar:to_svg(), 'data-fontsize="14"')
  assert_equal(polar:to_scene().polar.legend.fontsize, 14)
end)

test("legend font size validates positive numbers", function()
  local fig = plt.figure()
  assert_error("fontsize must be >= 0.1", function()
    fig:legend({ fontsize = 0 })
  end)
  assert_error("fontsize must be a number", function()
    fig:legend({ fontsize = "big" })
  end)
end)
