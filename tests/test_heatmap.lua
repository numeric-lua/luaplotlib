local plt = require("luaplotlib")

test("renders a heatmap with a colorbar", function()
  local fig = plt.figure({ width = 640, height = 480 })
  fig:imshow({ { 1, 2, 3 }, { 4, 5, 6 }, { 7, 8, 9 } })
  local svg = fig:to_svg()
  assert_equal(select(2, svg:gsub('class="heatmap%-cell"', "")), 9)
  assert_contains(svg, 'class="colorbar"')
  assert_contains(svg, 'class="heatmap"')
  assert_contains(svg, 'data-xscale="linear"')
  local path = (TMPDIR or "/tmp") .. "/luaplotlib-heatmap.svg"
  assert_equal(fig:savefig(path), path)
  os.remove(path)
end)

test("imshow supports explicit limits and rejects ragged matrices", function()
  local fig = plt.figure()
  fig:imshow({ { 0, 1 }, { 1, 0 } }, { vmin = 0, vmax = 2, colorbar = false })
  local svg = fig:to_svg()
  assert_equal(select(2, svg:gsub('class="heatmap%-cell"', "")), 4)
  assert_not_contains(svg, 'class="colorbar"')
  assert_error("equal length", function()
    fig:imshow({ { 1, 2 }, { 3 } })
  end)
end)
