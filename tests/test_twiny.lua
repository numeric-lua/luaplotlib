local plt = require("luaplotlib")

test("renders a secondary x axis on top", function()
  local fig = plt.figure({ width = 700, height = 460 })
  fig:plot({ 1, 2, 3 }, { 10, 20, 30 })
  local twiny = fig:twiny()
  assert_true(twiny == fig:twiny())
  twiny:plot({ 100, 200, 300 }, { 1, 2, 3 }, { color = "#d62728" })
  twiny:xlabel("top")
  twiny:xlim(50, 350)
  local svg = fig:to_svg()
  assert_contains(svg, 'class="twiny-axis"')
  assert_contains(svg, 'twiny-series')
  assert_contains(svg, '>top<')
  assert_contains(svg, '>300<')
  assert_contains(svg, "#d62728")
end)
