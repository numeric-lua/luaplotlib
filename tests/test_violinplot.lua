local plt = require("luaplotlib")

local function group_attr(svg, pattern)
  local group = assert(svg:match(pattern))
  local result = {}
  for key, value in group:gmatch('([%w:-]+)="([^"]*)"') do
    result[key] = value
  end
  return result
end

test("violinplot draws KDE bodies with median and quartile marks", function()
  local fig = plt.figure({ width = 760, height = 500 })
  fig:violinplot({ { 1, 2, 2, 3, 4, 5 }, { 2, 3, 3, 4, 6 } }, {
    labels = { "alpha", "beta" }, showextrema = true,
  })
  local svg = fig:to_svg()
  assert_well_formed_svg(svg)
  assert_equal(count_occurrences(svg, 'class="series series-violin"'), 2)
  assert_equal(count_occurrences(svg, 'class="violin-body"'), 2)
  assert_equal(count_occurrences(svg, 'class="violin-center"'), 2)
  assert_equal(count_occurrences(svg, 'class="violin-median"'), 2)
  assert_equal(count_occurrences(svg, 'class="violin-quartile"'), 4)
  assert_equal(count_occurrences(svg, 'class="violin-extrema"'), 4)
  assert_contains(svg, 'data-position="1"')
  assert_contains(svg, 'data-position="2"')
  assert_contains(svg, 'data-bandwidth="')
  assert_contains(svg, '>alpha</text>')
  assert_contains(svg, '>beta</text>')

  local scene = fig:to_scene()
  local first = scene.series[1]
  assert_equal(first.kind, "violin")
  assert_equal(first.position, 1)
  assert_equal(#first.values, 6)
  assert_equal(#first.densities, first.points)
  assert_equal(#first.body_x, #first.body_y)
  assert_true(#first.body_x > first.points)
  assert_equal(first.minimum, 1)
  assert_equal(first.maximum, 5)
  assert_equal(first.median, 2.5)
  assert_equal(first.showextrema, true)
  assert_equal(first.showmedians, true)
  assert_equal(first.showquartiles, true)
  assert_true(first.densities[1] == 0)
  assert_true(first.densities[first.points] == 0)
  assert_true(scene.xlim[1] < 1 and scene.xlim[2] > 2)
  assert_true(scene.ylim[1] < 1 and scene.ylim[2] > 6)
end)

test("violinplot inner marks and colors are configurable", function()
  local fig = plt.figure({ width = 700, height = 460 })
  fig:violinplot({ { 1, 2, 3, 4 }, { 2, 3, 4, 5 } }, {
    colors = { "#1f77b4", "#d62728" },
    showextrema = false, showmedians = false, showquartiles = false,
    alpha = 0.35, edgecolor = "#111111", linewidth = 2,
  })
  local svg = fig:to_svg()
  assert_not_contains(svg, 'class="violin-extrema"')
  assert_not_contains(svg, 'class="violin-median"')
  assert_not_contains(svg, 'class="violin-quartile"')
  assert_contains(svg, 'fill="#1f77b4" fill-opacity="0.35" ' ..
    'stroke="#111111" stroke-width="2"')
  assert_contains(svg, 'fill="#d62728"')
  local scene = fig:to_scene()
  assert_equal(scene.series[2].showextrema, false)
  assert_equal(scene.series[1].style.alpha, 0.35)
end)

test("violinplot positions, widths, and legend labels are exported", function()
  local fig = plt.figure({ width = 720, height = 460 })
  fig:violinplot({ { 1, 2, 3 }, { 3, 4, 5 } }, {
    positions = { 10, 14 }, width = 0.4,
    labels = { "first", "second" }, label = "distribution",
  })
  fig:legend({ loc = "upper right" })
  local svg = fig:to_svg()
  local first = group_attr(svg, '<g class="series series%-violin"[^>]*>')
  assert_equal(first["data-position"], "10")
  local scene = fig:to_scene()
  assert_equal(scene.series[1].width, 1.6)
  assert_equal(scene.series[2].width, 1.6)
  assert_equal(scene.category_ticks[1].position, 10)
  assert_equal(scene.category_ticks[2].label, "second")
  assert_contains(svg, 'class="legend"')
  assert_contains(svg, '>first</text>')
  assert_contains(svg, '>second</text>')
end)

test("violinplot handles a single repeated sample without non-finite geometry", function()
  local fig = plt.figure({ width = 600, height = 420 })
  fig:violinplot({ 4, 4, 4 }, { points = 24 })
  local svg = fig:to_svg()
  assert_well_formed_svg(svg)
  assert_equal(count_occurrences(svg, 'class="violin-body"'), 1)
  assert_equal(count_occurrences(svg, 'class="violin-extrema"'), 2)
  assert_not_contains(svg:lower(), "nan")
  assert_not_contains(svg:lower(), "inf")
  local scene = fig:to_scene().series[1]
  assert_equal(scene.minimum, 2)
  assert_equal(scene.maximum, 6)
  assert_equal(scene.median, 4)
  assert_true(scene.bandwidth > 0)
end)

test("violinplot validation rejects malformed samples and options", function()
  local fig = plt.figure()
  assert_error("non%-empty", function() fig:violinplot({}) end)
  assert_error("must not be empty", function() fig:violinplot({ {} }) end)
  assert_error("labels", function()
    fig:violinplot({ { 1 }, { 2 } }, { labels = { "only" } })
  end)
  assert_error("colors", function()
    fig:violinplot({ { 1 }, { 2 } }, { colors = { "#000000" } })
  end)
  assert_error("cannot both be set", function()
    fig:violinplot({ { 1 } }, {
      colors = { "#000000" }, color = "#ffffff",
    })
  end)
  assert_error("positions", function()
    fig:violinplot({ { 1 } }, { positions = { 1, 2 } })
  end)
  assert_error("width", function()
    fig:violinplot({ { 1 } }, { width = 0 })
  end)
  assert_error("points", function()
    fig:violinplot({ { 1 } }, { points = 5 })
  end)
  assert_error("bandwidth", function()
    fig:violinplot({ { 1 } }, { bandwidth = 0 })
  end)
  assert_error("showextrema", function()
    fig:violinplot({ { 1 } }, { showextrema = "yes" })
  end)
  assert_error("showmedians", function()
    fig:violinplot({ { 1 } }, { showmedians = 1 })
  end)
  assert_error("showquartiles", function()
    fig:violinplot({ { 1 } }, { showquartiles = "yes" })
  end)
  assert_error("alpha", function()
    fig:violinplot({ { 1 } }, { alpha = 2 })
  end)
  assert_error("linewidth", function()
    fig:violinplot({ { 1 } }, { linewidth = -1 })
  end)
  assert_error("edgecolor", function()
    fig:violinplot({ { 1 } }, { edgecolor = "not a color!" })
  end)
end)
