local plt = require("luaplotlib")

test("custom ticks and formatters replace automatic labels", function()
  local fig = plt.figure({ width = 640, height = 480 })
  fig:plot({ 1, 2, 3 }, { 10, 20, 30 })
  fig:xticks({ 1, 3 }, { "start", "end" })
  fig:yticks({ 10, 30 })
  fig:ytick_format(function(value) return value .. "%" end)
  local svg = fig:to_svg()
  assert_contains(svg, ">start<")
  assert_contains(svg, ">end<")
  assert_contains(svg, ">10%<")
  assert_contains(svg, ">30%<")
end)

test("tick inputs are validated", function()
  local fig = plt.figure()
  assert_error("non%-empty", function() fig:xticks({}) end)
  assert_error("must match", function()
    fig:xticks({ 1, 2 }, { "one" })
  end)
  assert_error("function", function() fig:ytick_format("bad") end)
end)
