local plt = require("luaplotlib")

test("renders fill_between, step, stem, and stackplot", function()
  local fig = plt.figure({ width = 700, height = 480 })
  fig:fill_between({ 1, 2, 3 }, { 1, 2, 1 }, { 2, 3, 2 }, { label = "band" })
  fig:step({ 1, 2, 3 }, { 1, 2, 1 }, { where = "mid" })
  fig:stem({ 1, 2, 3 }, { 3, 1, 2 })
  fig:stackplot({ 1, 2, 3 }, { { 1, 2, 3 }, { 2, 1, 1 } },
    { labels = { "A", "B" }, alpha = 0.7 })
  local svg = fig:to_svg()
  assert_contains(svg, 'class="fill-between"')
  assert_contains(svg, 'series-step')
  assert_contains(svg, 'class="stem-line"')
  assert_contains(svg, 'class="stem-marker"')
  assert_equal(select(2, svg:gsub('class="fill%-between"', "")), 3)
end)

test("validates fill/step/stem lengths", function()
  local fig = plt.figure()
  assert_error("same length", function()
    fig:fill_between({ 1, 2 }, { 1 }, { 2 })
  end)
  assert_error("same length", function() fig:step({ 1, 2 }, { 1 }) end)
  assert_error("where", function() fig:step({ 1 }, { 1 }, { where = "bad" }) end)
  assert_error("same length", function() fig:stem({ 1, 2 }, { 1 }) end)
  assert_error("non%-empty", function() fig:stackplot({ 1 }, {}) end)
end)
