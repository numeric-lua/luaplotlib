local plt = require("luaplotlib")

test("axis labels have no extra padding by default", function()
  local fig = plt.figure()
  fig:plot({ 1, 2 }, { 1, 2 })
  fig:xlabel("x")
  fig:ylabel("y")
  local svg = fig:to_svg()
  assert_not_contains(svg, "data-xlabel-pad")
  local scene = fig:to_scene()
  assert_equal(scene.xlabel_pad, 0)
  assert_equal(scene.ylabel_pad, 0)
end)

test("axis label padding expands the plot margins", function()
  local fig = plt.figure({ width = 640, height = 480 })
  fig:plot({ 1, 2 }, { 1, 2 })
  fig:xlabel("x", { labelpad = 20 })
  fig:ylabel("y", { labelpad = 15 })
  local svg = fig:to_svg()
  assert_contains(svg, 'data-xlabel-pad="20" data-ylabel-pad="15"')
  assert_contains(svg, 'class="spine" d="M 87 48 L 87 394 L 614.4 394"')
  local scene = fig:to_scene()
  assert_equal(scene.xlabel_pad, 20)
  assert_equal(scene.ylabel_pad, 15)
end)

test("axis label padding is retained when text changes without options", function()
  local fig = plt.figure()
  fig:plot({ 1, 2 }, { 1, 2 })
  fig:xlabel("first", { labelpad = 8 })
  fig:xlabel("second")
  assert_contains(fig:to_svg(), 'data-xlabel-pad="8"')
  assert_equal(fig:to_scene().xlabel_pad, 8)
end)

test("axis label padding validates non-negative numbers", function()
  local fig = plt.figure()
  assert_error("labelpad must be >= 0", function()
    fig:xlabel("x", { labelpad = -1 })
  end)
  assert_error("labelpad must be a number", function()
    fig:ylabel("y", { labelpad = "wide" })
  end)
  assert_error("unsupported xlabel option", function()
    fig:xlabel("x", { pad = 2 })
  end)
end)
