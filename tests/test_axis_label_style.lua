local plt = require("luaplotlib")

test("axis labels keep their default style", function()
  local fig = plt.figure()
  fig:plot({ 1, 2 }, { 1, 2 })
  fig:xlabel("x")
  fig:ylabel("y")
  local svg = fig:to_svg()
  assert_match(svg, 'class="xlabel" x="[^"]*" y="[^"]*" font%-size="13" fill="#222222"')
  assert_match(svg, 'class="ylabel" x="[^"]*" y="[^"]*" font%-size="13" fill="#222222"')
  local scene = fig:to_scene()
  assert_equal(scene.xlabel_fontsize, 13)
  assert_equal(scene.ylabel_fontsize, 13)
  assert_equal(scene.xlabel_color, "#222222")
  assert_equal(scene.ylabel_color, "#222222")
end)

test("axis label size and color are configurable", function()
  local fig = plt.figure({ width = 720, height = 480 })
  fig:plot({ 1, 2 }, { 1, 2 })
  fig:xlabel("x", { fontsize = 17, color = "#1e3a8a" })
  fig:ylabel("y", { fontsize = 16, color = "#7c2d12" })
  local svg = fig:to_svg()
  assert_match(svg, 'class="xlabel" x="[^"]*" y="[^"]*" font%-size="17" fill="#1e3a8a"')
  assert_match(svg, 'class="ylabel" x="[^"]*" y="[^"]*" font%-size="16" fill="#7c2d12"')
  assert_contains(svg, 'class="spine" d="M 76 48 L 76 410 L 692 410"')
  local scene = fig:to_scene()
  assert_equal(scene.xlabel_fontsize, 17)
  assert_equal(scene.ylabel_fontsize, 16)
  assert_equal(scene.xlabel_color, "#1e3a8a")
  assert_equal(scene.ylabel_color, "#7c2d12")
end)

test("axis label style validates size and color", function()
  local fig = plt.figure()
  assert_error("fontsize must be >= 0.1", function()
    fig:xlabel("x", { fontsize = 0 })
  end)
  assert_error("color", function()
    fig:ylabel("y", { color = "12bad" })
  end)
  assert_error("unsupported xlabel option", function()
    fig:xlabel("x", { weight = "bold" })
  end)
end)
