local plt = require("luaplotlib")

local function count_rotated_labels(svg, angle)
  return count_occurrences(svg, 'transform="rotate(' .. angle .. ' ')
end

test("ytick_rotation rotates only the y tick labels", function()
  local fig = plt.figure({ width = 600, height = 400 })
  fig:plot({ 1, 2, 3 }, { 10, 20, 30 })
  fig:ytick_rotation(-45)
  local svg = fig:to_svg()
  assert_well_formed_svg(svg)
  local rotated = count_rotated_labels(svg, "-45")
  assert_true(rotated > 0, "expected rotated y tick labels")
  local y_count = select(2, svg:gsub('class="ticks y%-ticks"', ""))
  assert_equal(y_count, 1, "one y-tick group")
  local x_labels = svg:match('class="ticks x%-ticks"(.-)</g>') or ""
  assert_not_contains(x_labels, "rotate(", "x labels should remain horizontal")
end)

test("x and y rotations can be combined", function()
  local fig = plt.figure({ width = 700, height = 450 })
  fig:plot({ 1, 2, 3 }, { 3, 2, 1 })
  fig:xtick_rotation(30)
  fig:ytick_rotation(-60)
  local svg = fig:to_svg()
  assert_true(count_rotated_labels(svg, "30") > 0, "x labels should rotate")
  assert_true(count_rotated_labels(svg, "-60") > 0, "y labels should rotate")
  local scene = fig:to_scene()
  assert_equal(scene.xtick_rotation, 30, "scene x rotation")
  assert_equal(scene.ytick_rotation, -60, "scene y rotation")
end)

test("ytick_rotation also applies to twin y-axis labels", function()
  local fig = plt.figure({ width = 700, height = 450 })
  fig:plot({ 1, 2, 3 }, { 1, 2, 3 })
  fig:twinx():plot({ 1, 2, 3 }, { 6, 5, 4 })
  fig:ytick_rotation(45)
  local svg = fig:to_svg()
  assert_contains(svg, 'class="twin-axis"')
  assert_true(count_rotated_labels(svg, "45") >= 2,
    "primary and twin y labels should both rotate")
end)

test("ytick_rotation validates its angle", function()
  local fig = plt.figure()
  assert_error("integer", function() fig:ytick_rotation(12.5) end)
  assert_error("integer", function() fig:ytick_rotation("45") end)
  assert_error("%[-90, 90%]", function() fig:ytick_rotation(91) end)
  assert_error("%[-90, 90%]", function() fig:ytick_rotation(-91) end)
  assert_error("90%]", function() fig:ytick_rotation(0 / 0) end)
end)
