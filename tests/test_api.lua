-- Module entry, figure options, and method chaining.

local plt = require("luaplotlib")
local util = require("luaplotlib.util")

test("module exposes the public API without optional dependencies", function()
  assert_equal(type(plt.figure), "function")
  assert_equal(type(plt.Figure), "table")
  assert_equal(type(plt._VERSION), "string")
  assert_equal(plt._VERSION, "4.24.0")
  assert_equal(package.loaded["torch"], nil, "require('luaplotlib') must not load torch")
end)

test("default canvas is 640x480 at 100 dpi", function()
  local fig = plt.figure()
  assert_equal(fig.width, 640)
  assert_equal(fig.height, 480)
  assert_equal(fig.dpi, 100)
  local svg = fig:to_svg()
  assert_contains(svg, 'width="640" height="480" viewBox="0 0 640 480"')
  assert_contains(svg, 'data-dpi="100"')
  assert_well_formed_svg(svg)
end)

test("dpi controls the default canvas size", function()
  local fig = plt.figure({ dpi = 200 })
  assert_equal(fig.width, 1280)
  assert_equal(fig.height, 960)
  local svg = fig:to_svg()
  assert_contains(svg, 'width="1280" height="960"')
  assert_contains(svg, 'viewBox="0 0 1280 960"')
end)

test("explicit width and height are SVG user units", function()
  local fig = plt.figure({ width = 800, height = 600, dpi = 150 })
  assert_equal(fig.width, 800)
  assert_equal(fig.height, 600)
  local svg = fig:to_svg()
  assert_contains(svg, 'width="800" height="600" viewBox="0 0 800 600"')
  assert_contains(svg, 'data-dpi="150"')
  assert_well_formed_svg(svg)
end)

test("drawing and configuration methods chain", function()
  local fig = plt.figure({ width = 640, height = 480 })
  assert_equal(fig:plot({ 1, 2 }, { 3, 4 }), fig)
  assert_equal(fig:scatter({ 1, 2 }, { 3, 4 }), fig)
  assert_equal(fig:hist({ 1, 2, 3 }), fig)
  assert_equal(fig:bar({ "a", "b" }, { 1, 2 }), fig)
  assert_equal(fig:title("t"), fig)
  assert_equal(fig:xlabel("x"), fig)
  assert_equal(fig:ylabel("y"), fig)
  assert_equal(fig:legend(), fig)
  assert_equal(fig:grid(true), fig)
  assert_equal(fig:xlim(0, 3), fig)
  assert_equal(fig:ylim(0, 5), fig)
  assert_equal(fig:xscale("log"), fig)
  assert_equal(fig:yscale("log"), fig)
  assert_equal(fig:xscale("linear"), fig)
  assert_equal(fig:yscale("linear"), fig)
  assert_equal(fig:grid(false), fig)
  assert_well_formed_svg(fig:to_svg())
end)

test("axis scales default to linear and can be set on the figure", function()
  local default = plt.figure()
  assert_equal(default._xscale, "linear")
  assert_equal(default._yscale, "linear")

  local configured = plt.figure({ xscale = "log", yscale = "log" })
  assert_equal(configured._xscale, "log")
  assert_equal(configured._yscale, "log")
  assert_contains(configured:to_svg(), 'data-xscale="log" data-yscale="log"')
end)

test("figures are independent", function()
  local first = plt.figure({ width = 400, height = 300 })
  local second = plt.figure({ width = 500, height = 350 })
  first:plot({ 1, 2 }, { 1, 2 })
  second:scatter({ 1, 2 }, { 2, 1 })
  assert_equal(#first._series, 1)
  assert_equal(#second._series, 1)
  assert_not_contains(first:to_svg(), 'class="point"')
  assert_contains(second:to_svg(), 'class="point"')
end)

test("input tables are copied at call time", function()
  local x = { 1, 2, 3 }
  local y = { 4, 5, 6 }
  local fig = plt.figure()
  fig:plot(x, y)
  x[1], y[1] = 100, 100
  local svg = fig:to_svg()
  assert_contains(svg, '<polyline class="line"')
  assert_not_contains(svg, 'points="100,')
end)

test("xml escaping handles entities and invalid control characters", function()
  local escaped = util.escape_xml([[<&>"']])
  assert_equal(escaped, "&lt;&amp;&gt;&quot;&apos;")
  local with_control = "safe" .. string.char(1) .. "text"
  assert_equal(util.escape_xml(with_control), "safe\239\191\189text")
  local unicode = "temperatura °C"
  assert_equal(util.escape_xml(unicode), unicode)
end)
