local plt = require("luaplotlib")

test("titles keep their default font styling", function()
  local fig = plt.figure()
  fig:plot({ 1, 2 }, { 1, 2 })
  fig:title("plain")
  local svg = fig:to_svg()
  assert_match(svg, 'class="title" x="[^"]*" y="[^"]*" font%-size="18" fill="#222222" text%-anchor="middle">plain</text>')
  local scene = fig:to_scene()
  assert_equal(scene.title_fontsize, 18)
  assert_equal(scene.title_color, "#222222")
end)

test("cartesian title size and color are configurable", function()
  local fig = plt.figure()
  fig:plot({ 1, 2 }, { 1, 2 })
  fig:title("styled", { fontsize = 24, color = "#0f172a" })
  local svg = fig:to_svg()
  assert_match(svg, 'class="title" x="[^"]*" y="[^"]*" font%-size="24" fill="#0f172a" text%-anchor="middle">styled</text>')
  local scene = fig:to_scene()
  assert_equal(scene.title_fontsize, 24)
  assert_equal(scene.title_color, "#0f172a")
end)

test("title styling carries through pie, polar, and subplots", function()
  local pie = plt.figure()
  pie:pie({ 1, 2, 3 }, { labels = { "a", "b", "c" } })
  pie:title("pie", { fontsize = 22, color = "#7c2d12" })
  assert_match(pie:to_svg(), 'class="title" x="[^"]*" y="28" font%-size="22" fill="#7c2d12"')

  local polar = plt.figure({ width = 480, height = 480 })
  polar:polar({ 0, 1 }, { 1, 1 })
  polar:title("polar", { fontsize = 20, color = "#14532d" })
  assert_match(polar:to_svg(), 'class="title" x="[^"]*" y="30" font%-size="20" fill="#14532d"')
  assert_equal(polar:to_scene().title_fontsize, 20)

  local subplots = plt.subplots(1, 2, { width = 640, height = 360 })
  subplots:title("grid", { fontsize = 26, color = "#1e3a8a" })
  assert_match(subplots:to_svg(), 'class="suptitle" x="[^"]*" y="[^"]*" font%-size="26" fill="#1e3a8a"')
  assert_equal(subplots:to_scene().title_fontsize, 26)
end)

test("title font options validate size and color", function()
  local fig = plt.figure()
  assert_error("fontsize must be >= 0.1", function()
    fig:title("x", { fontsize = 0 })
  end)
  assert_error("color", function()
    fig:title("x", { color = "12bad" })
  end)
  local subplots = plt.subplots(1, 1)
  assert_error("fontsize must be >= 0.1", function()
    subplots:title("x", { fontsize = 0 })
  end)
end)
