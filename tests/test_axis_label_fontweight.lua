local plt = require("luaplotlib")

test("axis labels default to normal and accept bold", function()
  local fig = plt.figure()
  fig:plot({ 1, 2 }, { 1, 2 })
  fig:xlabel("x", { fontweight = "bold" })
  fig:ylabel("y", { fontweight = "bold" })
  local svg = fig:to_svg()
  assert_match(svg, 'class="xlabel"[^>]*font%-weight="bold"')
  assert_match(svg, 'class="ylabel"[^>]*font%-weight="bold"')
  local scene = fig:to_scene()
  assert_equal(scene.xlabel_fontweight, "bold")
  assert_equal(scene.ylabel_fontweight, "bold")
end)

test("axis label fontweight validates allowed values", function()
  local fig = plt.figure()
  assert_error("fontweight must be 'normal' or 'bold'", function()
    fig:xlabel("x", { fontweight = "heavy" })
  end)
end)
