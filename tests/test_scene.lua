-- Renderer-agnostic scene export tests.

local scene = require("luaplotlib.scene")
local luaplotlib = require("luaplotlib")

test("exports line and scatter series", function()
  local figure = luaplotlib.figure({ width = 400, height = 300 })
  figure:plot({ 1, 2, 3 }, { 2, 4, 3 }, { color = "#112233", label = "line" })
  figure:scatter({ 1, 3 }, { 1, 3 }, { color = "#445566" })
  local exported = scene.from_figure(figure)
  assert_equal(exported.type, "luaplotlib")
  assert_equal(exported.width, 400)
  assert_equal(#exported.series, 2)
  assert_equal(exported.series[1].kind, "line")
  assert_equal(exported.series[1].style.color, "#112233")
  assert_equal(exported.series[1].x[2], 2)
  assert_equal(exported.series[2].kind, "scatter")
  assert_true(exported.xlim[1] < 1 and exported.xlim[2] > 3)
  assert_true(exported.ylim[1] < 1 and exported.ylim[2] > 4)
end)

test("exports bar and hist geometry", function()
  local figure = luaplotlib.figure()
  figure:bar({ "a", "b" }, { 2, 5 })
  figure:hist({ 1, 1, 2, 3 }, { bins = 2 })
  local exported = scene.from_figure(figure)
  assert_equal(exported.series[1].kind, "bar")
  assert_equal(exported.series[1].y[2], 5)
  assert_equal(exported.series[2].kind, "hist")
  assert_equal(#exported.series[2].edges, 3)
  assert_equal(#exported.series[2].counts, 2)
  assert_true(exported.xlim[2] >= 3)
end)

test("exports grouped offsets while preserving category centers", function()
  local figure = luaplotlib.figure()
  figure:bar({ "a", "b" }, {
    { 2, 4 },
    { 3, 1 },
  }, { labels = { "left", "right" } })
  local exported = figure:to_scene()
  assert_equal(#exported.series, 2)
  local left, right = exported.series[1], exported.series[2]
  assert_equal(left.mode, "grouped")
  assert_equal(right.mode, "grouped")
  assert_true(left.offset < 0 and right.offset > 0)
  assert_equal(left.x[1], 1)
  assert_equal(right.x[1], 1)
  assert_equal(left.offsets[2], left.offset)
  assert_equal(left.width, 0.4)
  assert_equal(left.style.label, "left")
  assert_equal(right.style.label, "right")
end)

test("exports stacked bottoms, total heights, and negative stacks", function()
  local figure = luaplotlib.figure()
  figure:bar({ "a", "b" }, {
    { 2, 3 },
    { 4, -1 },
  }, { stacked = true, labels = { "first", "second" } })
  local exported = figure:to_scene()
  local first, second = exported.series[1], exported.series[2]
  assert_equal(first.mode, "stacked")
  assert_equal(first.stacked, true)
  assert_equal(first.bottom[1], 0)
  assert_equal(first.bottom[2], 0)
  assert_equal(second.bottom[1], 2)
  assert_equal(second.bottom[2], 0)
  assert_equal(second.top[1], 6)
  assert_equal(second.top[2], -1)
  assert_true(exported.ylim[1] < -1)
  assert_true(exported.ylim[2] > 6)

  local negative = luaplotlib.figure()
  negative:bar({ "a" }, {
    { 2 },
    { 3 },
    { -4 },
    { -1 },
  }, { stacked = true })
  local stacks = negative:to_scene().series
  assert_equal(stacks[2].bottom[1], 2)
  assert_equal(stacks[2].top[1], 5)
  assert_equal(stacks[3].bottom[1], 0)
  assert_equal(stacks[3].top[1], -4)
  assert_equal(stacks[4].bottom[1], -4)
  assert_equal(stacks[4].top[1], -5)
  local ylim = negative:to_scene().ylim
  assert_true(ylim[1] < -5)
  assert_true(ylim[2] > 5)
end)

test("honors explicit limits and does not mutate the figure", function()
  local figure = luaplotlib.figure():xlim(0, 10):ylim(-2, 2)
  figure:plot({ 1, 2 }, { -1, 1 })
  local exported = scene.from_figure(figure)
  assert_equal(exported.xlim[1], 0)
  assert_equal(exported.xlim[2], 10)
  assert_equal(exported.ylim[1], -2)
  assert_equal(exported.ylim[2], 2)
  assert_equal(figure._series[1].x[1], 1)
  exported.series[1].x[1] = 99
  assert_equal(figure._series[1].x[1], 1)
end)

test("empty figures still produce finite limits", function()
  local exported = scene.from_figure(luaplotlib.figure())
  assert_equal(exported.xlim[1], 0)
  assert_equal(exported.xlim[2], 1)
  assert_equal(exported.ylim[1], 0)
  assert_equal(exported.ylim[2], 1)
end)

test("Figure:to_scene delegates", function()
  local figure = luaplotlib.figure():plot({ 1, 2 }, { 3, 4 })
  local exported = figure:to_scene()
  assert_equal(exported.series[1].kind, "line")
end)

test("exports axis scales and keeps log limits positive", function()
  local figure = luaplotlib.figure({ xscale = "log", yscale = "log" })
  figure:plot({ 1, 10, 100 }, { 1, 100, 10000 })
  local exported = figure:to_scene()
  assert_equal(exported.xscale, "log")
  assert_equal(exported.yscale, "log")
  assert_true(exported.xlim[1] > 0 and exported.xlim[2] >= 100)
  assert_true(exported.ylim[1] > 0 and exported.ylim[2] >= 10000)
end)

test("exports error bars and includes their extents", function()
  local figure = luaplotlib.figure()
  figure:errorbar({ 2, 4 }, { 10, 20 }, { 1, 2 }, { 0.5, 1 }, {
    label = "errors", color = "#123456",
  })
  local exported = figure:to_scene()
  local series = exported.series[1]
  assert_equal(series.kind, "errorbar")
  assert_equal(series.yerr[2], 2)
  assert_equal(series.xerr[1], 0.5)
  assert_equal(series.style.capsize, 4)
  assert_equal(series.style.ecolor, "#123456")
  assert_true(exported.xlim[1] < 1.5)
  assert_true(exported.xlim[2] > 5)
  assert_true(exported.ylim[1] < 9)
  assert_true(exported.ylim[2] > 22)
end)

test("exports image, box, contour, and barh geometry", function()
  local figure = luaplotlib.figure()
  figure:imshow({ { 1, 2 }, { 3, 4 } })
  figure:boxplot({ { 1, 2, 3 }, { 4, 5, 6 } })
  figure:contour({ { 0, 1 }, { 1, 0 } }, { levels = 1 })
  figure:barh({ "a", "b" }, { 2, 4 }, { show_values = true })
  local exported = figure:to_scene()
  assert_equal(exported.series[1].kind, "image")
  assert_equal(exported.series[1].values[2][2], 4)
  assert_equal(exported.series[2].kind, "box")
  assert_equal(exported.series[2].median, 2)
  assert_equal(exported.series[4].kind, "contour")
  assert_true(#exported.series[4].segments > 0)
  assert_equal(exported.series[5].kind, "barh")
  assert_equal(exported.series[5].show_values, true)
  assert_true(exported.xlim[2] >= 2)
end)

test("exports twin axis metadata and series", function()
  local figure = luaplotlib.figure()
  figure:plot({ 1, 2 }, { 1, 2 })
  local twin = figure:twinx()
  twin:plot({ 1, 2 }, { 10, 20 }, { color = "#123456" })
  twin:ylabel("right")
  local exported = figure:to_scene()
  assert_true(exported.twin ~= nil)
  assert_equal(exported.twin.ylabel, "right")
  assert_equal(#exported.twin.series, 1)
  assert_equal(exported.twin.series[1].style.color, "#123456")
end)

test("exports pie and donut slices", function()
  local figure = luaplotlib.figure()
  figure:donut({ 2, 3 }, { labels = { "A", "B" } })
  local exported = figure:to_scene()
  assert_true(exported.pie ~= nil)
  assert_equal(#exported.pie.slices, 2)
  assert_true(exported.pie.inner_radius > 0)
  assert_equal(exported.pie.slices[1].label, "A")
end)
